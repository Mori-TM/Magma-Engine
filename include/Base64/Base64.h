DWORD Bas64CalcRequiredSize(DWORD size)
{
    return (size / 3) * 4 + 1;
}

void Base64Encode(BYTE* src, DWORD src_len, BYTE* dst, DWORD* dst_len)
{
    const BYTE encode_tab[] = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/=";

    BYTE* s = src;
    BYTE* d = dst;
    DWORD len = src_len;

    BYTE b;
    BYTE c = 0;
    while (len > 0) {

        // first byte
        b = *s >> 2;
        // 1. sixpack
        *d = encode_tab[b];
        d++;
        c = *s & 0x03;


        // second byte
        s++; len--;
        b = *s >> 4;
        c = c << 4;
        b = b | c;
        // 2. sixpack
        *d = encode_tab[b];
        d++;
        c = *s & 0x0f;

        if (len <= 0) {
            *d = '=';
            d++;
            *d = '=';
            d++;
            break;
        }

        // third byte
        s++; len--;
        b = *s;
        b = b >> 6;
        c = c << 2;
        b = b | c;
        // 3. sixpack
        *d = encode_tab[b];
        d++;
        c = *s & 0x3f;

        if (len <= 0) {
            *d = '=';
            d++;
            break;
        }

        // 4. sixpack
        b = c;
        *d = encode_tab[b];
        d++;
        c = 0;

        s++; len--;
    }
    *d = 0;
    *dst_len = d - dst;
    return;
}

